// Builds the runtime into one minified ES module and writes it, with its
// sha256, into src/compiler/runtime.generated.ts for the compiler to inline.
// runtime-lock.json pins each runtime version to its hash: building a different
// bundle under a version already locked fails, so the same version always
// draws apps the same way. Bump the version in package.json to change it.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const { version } = JSON.parse(readFileSync(new URL("./package.json", import.meta.url), "utf8"));
const result = await build({
  entryPoints: ["src/runtime/main.tsx"],
  bundle: true,
  minify: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  legalComments: "none",
  charset: "utf8",
  alias: { react: "preact/compat", "react-dom": "preact/compat", "react-dom/client": "preact/compat/client", "react/jsx-runtime": "preact/jsx-runtime" },
  jsx: "automatic",
  jsxImportSource: "preact",
  define: { "process.env.NODE_ENV": '"production"' },
  write: false,
  metafile: true,
  logLevel: "error",
});
const js = result.outputFiles[0].text;
const sha256 = createHash("sha256").update(js).digest("hex");

const lockFile = new URL("./runtime-lock.json", import.meta.url);
const lock = JSON.parse(readFileSync(lockFile, "utf8"));
if (lock[version] && lock[version] !== sha256 && process.env.RELOCK !== "1") {
  console.error(`runtime ${version} is locked to ${lock[version]}, but this build is ${sha256}. Bump the version, or RELOCK=1 while ${version} is unreleased.`);
  process.exit(1);
}
lock[version] = sha256;
writeFileSync(lockFile, JSON.stringify(lock, null, 2) + "\n");
writeFileSync(
  new URL("./src/compiler/runtime.generated.ts", import.meta.url),
  `// Generated by build.mjs: the runtime bundle. Do not edit.\nexport const RUNTIME_VERSION = ${JSON.stringify(version)};\nexport const RUNTIME_SHA256 = ${JSON.stringify(sha256)};\nexport const RUNTIME_JS = ${JSON.stringify(js)};\n`,
);
// Every package in the bundle, with its licence, for THIRD_PARTY_LICENSES.txt:
// the bundle carries their code, so the package carries their notices.
const roots = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const at = input.lastIndexOf("node_modules/");
  if (at < 0) continue;
  const rest = input.slice(at + "node_modules/".length).split("/");
  roots.add(input.slice(0, at) + "node_modules/" + rest.slice(0, rest[0].startsWith("@") ? 2 : 1).join("/"));
}
const notices = [...roots]
  .map((root) => {
    const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
    const file = readdirSync(root).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    let text = file ? readFileSync(join(root, file), "utf8").trim() : null;
    // A package without its own licence file may sit in a repo that has one (A2UI's renderers do).
    if (!text && existsSync(join(dirname(root), "LICENSE"))) text = readFileSync(join(dirname(root), "LICENSE"), "utf8").trim();
    return {
      name: pkg.name,
      version: pkg.version,
      license: pkg.license ?? "see below",
      text: text ?? `No licence file shipped; ${pkg.name} declares ${pkg.license}.`,
    };
  })
  .sort((a, b) => (a.name < b.name ? -1 : 1));
writeFileSync(
  new URL("./THIRD_PARTY_LICENSES.txt", import.meta.url),
  `The CloudCrane app runtime (inlined in every page the compiler builds) contains code from these packages.\n\n` +
    notices.map((n) => `${n.name}@${n.version} (${n.license})\n${"-".repeat(72)}\n${n.text}\n`).join("\n"),
);

console.log(`runtime ${version}: ${js.length} bytes, sha256 ${sha256.slice(0, 12)}…`);
